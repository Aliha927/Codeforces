#include<bits/stdc++.h>
using namespace std;

int main(){
    int test_cases = 0;
    cin>>test_cases;
    while (test_cases > 0){
        long long n,m,k;
        cin>>n>>m>>k;
        if (k > m){
            cout<<"NO"<<endl;
            test_cases--;
            continue;
        }
        

        test_cases--;
    }
}